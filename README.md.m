# 2026 Congressional Race Tracker

A personal dashboard tracking competitive U.S. House and Senate races for the 2026 midterm elections.

## Features

- **Three panels**: Competitive House races (Toss-up), Competitive Senate races, and Leaning House seats
- **Six rating sources**: Cook Political Report, Sabato's Crystal Ball, 270toWin, Inside Elections, Ballotpedia
- **Consensus column**: Automatically averages all available source ratings
- **Tilt ratings**: Captures slight-edge ratings (Tilt D / Tilt R) used by Sabato and Inside Elections
- **Recent changes box**: Documents what changed since the last refresh on each tab
- **Sortable columns**: Click any column header to sort
- **Color coded**: Blue shades for Dem-leaning, yellow for Toss-up, red shades for Rep-leaning
- **Notes column**: Cook Political Report race summaries on the Competitive House tab

